"""MarketDataSource: what data ingestion (collector, backfill, depth probe) needs from a broker.

Implemented by ``MT5Broker``. Frames use the raw schemas in ``aurum.data.schemas`` and UTC
times; ``tick_frame``/``rate_frame`` return ``start <= time < end`` (rate: completed bars only).
"""

from datetime import datetime
from typing import Any, Protocol

import polars as pl

from aurum.core.models import AccountSnapshot, SymbolSpec
from aurum.core.timeframes import Timeframe


class MarketDataSource(Protocol):
    def connect(self) -> None: ...
    def disconnect(self) -> None: ...
    def is_connected(self) -> bool: ...
    def resolve_symbol(self) -> str: ...
    def account_info(self) -> AccountSnapshot: ...
    def symbol_info(self, symbol: str) -> SymbolSpec: ...
    def symbol_snapshot(self, symbol: str) -> dict[str, Any]: ...
    def tick_frame(self, symbol: str, start: datetime, end: datetime) -> pl.DataFrame: ...
    def rate_frame(
        self, symbol: str, timeframe: Timeframe, start: datetime, end: datetime
    ) -> pl.DataFrame: ...
